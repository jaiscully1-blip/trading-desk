// One-off: bakes the world outline into src/data/worldLand.ts so the map draws instantly (no topology parsing in the browser).
// Run: node scripts/bake-map.mjs   (needs d3-geo, topojson-client, world-atlas, already dev/prod deps)
import { readFileSync, writeFileSync } from 'node:fs';
import { geoNaturalEarth1, geoPath, geoGraticule10 } from 'd3-geo';
import { feature } from 'topojson-client';

const W = 960, H = 500;
const proj = geoNaturalEarth1().fitSize([W, H], { type: 'Sphere' });
const path = geoPath(proj).digits ? geoPath(proj).digits(1) : geoPath(proj);
const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-110m.json', 'utf8'));
const land = feature(topo, topo.objects.countries);
// one path for all land, 1 decimal place: small and a single DOM node
const d = land.features.map((f) => path(f) ?? '').join('');
const out = `// GENERATED by scripts/bake-map.mjs: world outline (Natural Earth projection, ${W}x${H}). Do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const MAP_SCALE = ${proj.scale()};
export const MAP_TX = ${proj.translate()[0]};
export const MAP_TY = ${proj.translate()[1]};
export const LAND = ${JSON.stringify(d)};
export const SPHERE = ${JSON.stringify(path({ type: 'Sphere' }) ?? '')};
export const GRATICULE = ${JSON.stringify(path(geoGraticule10()) ?? '')};
`;
writeFileSync('src/data/worldLand.ts', out);
console.log('land path chars:', d.length, 'scale', proj.scale(), 'translate', proj.translate());
