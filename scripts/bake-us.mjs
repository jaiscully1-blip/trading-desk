// One-off: bakes US state outlines (us-atlas 3.0.1, ISC, already Albers USA projected to 975x610) into src/data/usStates.ts,
// keyed by postal code, so the distress map draws instantly. Run: node scripts/bake-us.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';

const FIPS = { '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC', '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY', '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT', '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH', '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT', '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV', '55': 'WI', '56': 'WY' };
const topo = JSON.parse(readFileSync('node_modules/us-atlas/states-albers-10m.json', 'utf8'));
const path = geoPath().digits(0);
const states = {};
for (const f of feature(topo, topo.objects.states).features) { const k = FIPS[f.id]; if (k) states[k] = path(f); }
const centers = Object.fromEntries(feature(topo, topo.objects.states).features.filter((f) => FIPS[f.id]).map((f) => [FIPS[f.id], path.centroid(f).map(Math.round)]));
const out = `// GENERATED by scripts/bake-us.mjs from us-atlas 3.0.1 (ISC): US states, Albers USA projection (975x610). Do not edit by hand.
// Dots use the same projection: d3-geo geoAlbersUsa().scale(1300).translate([487.5, 305]).
export const US_W = 975;
export const US_H = 610;
export const US_STATES: Record<string, string> = ${JSON.stringify(states)};
export const US_CENTERS: Record<string, [number, number]> = ${JSON.stringify(centers)};
export const US_MESH = ${JSON.stringify(path(mesh(topo, topo.objects.states, (a, b) => a !== b)))};
`;
writeFileSync('src/data/usStates.ts', out);
console.log('bytes', out.length);
